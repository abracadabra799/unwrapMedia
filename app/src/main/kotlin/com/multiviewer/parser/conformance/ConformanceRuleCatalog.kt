package com.multiviewer.parser.conformance

/**
 * Inventory of the IDs emitted by parser.integrity, including conditional findings.
 * Absence of a finding does not establish PASS; the analyzer must retain it as NOT_CHECKED.
 * Parser warnings and inspection errors are separate evidence, not format rules.
 */
fun rulesFor(format: String): List<ConformanceRule> = when (format) {
    "AIFC" -> catalog.getValue("AIFF")
    else -> catalog[format].orEmpty()
}

private fun structuralRules(prefix: String, vararg entries: Pair<String, String>): List<ConformanceRule> =
    entries.map { (id, title) ->
        ConformanceRule(
            "$prefix.$id", title, "unwrapMedia structural check", null,
            "$title; 기존 바이트·구조 검사 범위 / Existing byte/structure check only; not full codec syntax conformance",
        )
    }

private fun pngRule(id: String, title: String, scope: String) = ConformanceRule(
    "png.$id", title, "W3C PNG Third Edition", "https://www.w3.org/TR/png-3/", scope,
